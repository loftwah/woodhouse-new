// Renders bounded WebP previews for the reviewed share-gallery image assets.
//
// The observed failure: the gallery used each full-resolution original as a
// small grid preview, so a phone downloaded several megabytes of PNG to look at
// six pictures. This writes a width-bounded preview per image asset under
// public/share/previews/ and records which ones exist, so the gallery can use
// them while the original stays the download and full-size target.
//
// Run without arguments to render and rewrite the manifest, or with --check to
// fail when the recorded previews and the files on disk disagree. Never modifies
// an original.

import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { gameMedia } from "../src/data/share-desk.ts";

const root = process.cwd();
const check = process.argv.includes("--check");
const previewDirectory = path.join(root, "public/share/previews");
const manifestPath = path.join(root, "src/data/share-previews.ts");
const maxWidth = 960;
const quality = 72;

const items = gameMedia
  .filter((asset) => asset.kind === "image" && asset.file.startsWith("/share/"))
  .map((asset) => ({
    id: asset.id,
    source: path.join(root, "public", asset.file),
    preview: path.join(previewDirectory, `${asset.id}.webp`)
  }));

if (!items.length) throw new Error("No share image assets were found to preview.");

async function recordedIds() {
  const source = await readFile(manifestPath, "utf8").catch(() => "");
  // Entries are one per line; the last one has no trailing comma under the
  // project's prettier config, so the comma is optional here.
  return [...source.matchAll(/^\s*"([^"]+)",?$/gm)].map((match) => match[1]);
}

if (check) {
  const recorded = new Set(await recordedIds());
  const findings = [];
  for (const item of items) {
    const source = await stat(item.source).catch(() => null);
    const preview = await stat(item.preview).catch(() => null);
    if (!source) {
      findings.push(`missing source asset ${item.id}`);
      continue;
    }
    if (recorded.has(item.id) !== Boolean(preview)) {
      findings.push(`recorded preview set disagrees with disk for ${item.id}`);
      continue;
    }
    if (preview && (preview.size === 0 || preview.size >= source.size))
      findings.push(`preview is not smaller than its source for ${item.id}`);
  }
  for (const id of recorded)
    if (!items.some((item) => item.id === id))
      findings.push(`recorded preview has no asset: ${id}`);
  if (findings.length) {
    for (const finding of findings) console.error(`Share preview check failed: ${finding}`);
    process.exitCode = 1;
  } else {
    console.log(
      `Share previews match: ${recorded.size} bounded previews for ${items.length} reviewed image assets.`
    );
  }
} else {
  await mkdir(previewDirectory, { recursive: true });
  const manifestFile = path.join(root, "output", "share-previews.json");
  await mkdir(path.dirname(manifestFile), { recursive: true });
  await writeFile(manifestFile, JSON.stringify({ maxWidth, quality, items }, null, 2) + "\n");
  const rendered = spawnSync(
    "python3",
    [path.join(root, "scripts/render-share-previews.py"), manifestFile],
    { stdio: "inherit" }
  );
  if (rendered.error) throw rendered.error;
  if (rendered.status !== 0) throw new Error("Preview rendering failed.");

  const kept = [];
  let total = 0;
  for (const item of items) {
    const source = await stat(item.source).catch(() => null);
    const preview = await stat(item.preview).catch(() => null);
    if (source && preview && preview.size > 0 && preview.size < source.size) {
      kept.push(item.id);
      total += preview.size;
    } else {
      await rm(item.preview, { force: true });
    }
  }
  kept.sort();
  const list = kept.map((id) => `  ${JSON.stringify(id)}`).join(",\n");
  await writeFile(
    manifestPath,
    `/**
 * Bounded gallery previews that exist under \`public/share/previews/\`.
 *
 * Generated by \`scripts/render-share-previews.mjs\`. The gallery shows these
 * instead of the full-resolution originals so a phone does not download tens of
 * megabytes to look at six small pictures; the original stays the download and
 * full-size target. \`pnpm run verify\` fails when this list and the files disagree.
 */
export const sharePreviews: readonly string[] = [
${list}
];
`
  );
  console.log(
    `Rendered ${kept.length} previews (${(total / 1048576).toFixed(1)} MB) and skipped ${items.length - kept.length} where the original was already small enough.`
  );
}
